'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path'), os=require('node:os');
const {execFileSync}=require('node:child_process');
const {_electron}=require('playwright');
const {waitUntil}=require('./support/wait-until.cjs');
const repo=path.resolve(__dirname,'../../..');
const output=path.join(repo,'apps/desktop/docs/product/evidence/2026-09-15-change-review');
fs.mkdirSync(output,{recursive:true});
async function main(){
  const baseline=process.argv.includes('--baseline');
  const existing=process.argv.find(a=>a.startsWith('--root='))?.slice(7);
  const root=existing||(baseline?'/tmp/vibe-comparison-baseline':fs.mkdtempSync(path.join(os.tmpdir(),'vibe-comparison-')));
  if(!baseline&&!existing)execFileSync('python',[path.join(__dirname,'support/prepare-comparison.py'),root],{timeout:180000});
  const source=path.join(root,'stage6-if-id.circ'), original=fs.readFileSync(source);
  const env={...process.env,XDG_CONFIG_HOME:root+'/config',VIBE_LOGISIM_STATE_DIR:root+'/state'};delete env.ELECTRON_RUN_AS_NODE;
  const launch=()=>_electron.launch({executablePath:require('electron'),args:[repo+'/apps/desktop',source,'--no-sandbox'],env});
  let app=await launch();
  let page;const errors=[];
  const session=()=>page.evaluate(()=>fetch('/api/session').then(r=>r.json()));
  const scene=()=>page.evaluate(()=>fetch('/api/circuit?name=IF_ID').then(r=>r.json()).then(d=>d.circuit));
  const idle=()=>page.waitForFunction(()=>document.querySelector('#appShell').getAttribute('aria-busy')==='false');
  const changed=async before=>{const s=await waitUntil(()=>session().then(s=>s.revision.id!==before&&s),{timeout:45000,label:'project change'});await idle();return s;};
  const reviewReady=async text=>{
    await waitUntil(()=>page.locator('#comparisonSummary').textContent().then(t=>t.includes(text)),{timeout:60000,label:'native comparison'});
    await waitUntil(()=>page.locator('#comparisonImage').evaluate(n=>!n.hidden&&n.complete&&n.naturalWidth>0));
  };
  const reviewRow=name=>page.locator('.comparison-row').filter({has:page.locator('strong',{hasText:name})});
  const history=async index=>{await page.locator('#proposalTab').click();await page.locator('#projectHistoryButton').click();await page.locator('.history-entry').nth(index).click();};
  const world=p=>page.locator('#circuitCanvas').evaluate((n,p)=>{const q=new DOMPoint(p.x,p.y).matrixTransform(n.getScreenCTM());return{x:q.x,y:q.y};},p);
  const connection=s=>Object.fromEntries(['Register','Pin'].map(factory=>[factory,s.components.find(c=>c.factory===factory&&c.label===(factory==='Register'?'ID.PC.REG':'ID.PC')).ends[0].netBits.map(b=>b.netId)]));
  try{
    page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
    await page.setViewportSize({width:1500,height:960});
    await page.locator('#proposalTab').click({timeout:60000});
    if(process.argv.includes('--history-only')){
      await page.locator('#projectHistoryButton').click();
      await page.locator('.history-entry').filter({hasText:'IF_ID 布局与控制线整理'}).click();
      await reviewReady('连接关系未变');
      assert.equal(await page.locator('#comparisonKind').textContent(),'工程历史');
      await page.locator('#comparisonEvidence').click();
      await waitUntil(()=>page.locator('#evidenceResults').textContent().then(t=>t.includes('尚未运行输入输出检查')));
      await page.locator('#evidenceBack').click();await reviewReady('连接关系未变');
      assert.equal(await page.locator('#comparisonKind').textContent(),'工程历史');
      assert.deepEqual(errors,[]);console.log('Historical candidate evidence returns to its history comparison');return;
    }
    await page.locator('.candidate-card').getByRole('button',{name:'查看改动'}).click({timeout:60000});
    if(baseline){
      await page.locator('#candidateModule').selectOption('IF_ID');
      await waitUntil(()=>page.locator('#candidateImage').evaluate(n=>n.complete&&n.naturalWidth>0));
      await page.screenshot({path:output+'/01-before.png'});return;
    }
    await reviewReady('连接关系未变');
    assert.equal(await page.locator('.comparison-row').count(),8);
    assert.match(await page.locator('#comparisonScope').textContent(),/气泡流水线/);
    await page.screenshot({path:output+'/02-after.png'});
    await reviewRow('封装引脚绑定更新').click();
    assert.match(await page.locator('#comparisonDetails').textContent(),/700,660/);
    assert.match(await page.locator('#comparisonDetails').textContent(),/700,620/);
    await page.locator('[data-category="layout"]').click();
    assert.equal(await page.locator('.comparison-row').count(),7);
    await page.locator('#comparisonSearch').fill('ID.PC');
    await reviewRow(/^ID.PC$/).click();
    assert.match(await page.locator('#comparisonDetails').textContent(),/\(640, 180\)/);
    assert.match(await page.locator('#comparisonDetails').textContent(),/\(740, 180\)/);
    const camera=()=>page.locator('#comparisonStage').evaluate(n=>({x:n.scrollLeft,y:n.scrollTop,scale:document.querySelector('#comparisonZoom').textContent}));
    const beforeCamera=await camera();
    await page.locator('#comparisonBefore').click();await reviewReady('连接关系未变');
    assert.deepEqual(await camera(),beforeCamera,'side switch preserves scale and position');
    await page.locator('#comparisonAfter').click();await reviewReady('连接关系未变');
    assert.deepEqual(await camera(),beforeCamera);
    await waitUntil(()=>page.locator('#comparisonDetailImage').getAttribute('href'));
    await page.screenshot({path:output+'/03-selected-move.png'});
    await page.setViewportSize({width:1100,height:760});await page.locator('#comparisonFit').click();
    await page.screenshot({path:output+'/07-compact-window.png'});
    assert.equal(await page.locator('#comparisonDialog').evaluate(n=>n.scrollWidth<=n.clientWidth),true,'review controls fit a smaller window');
    await page.setViewportSize({width:1500,height:960});
    if(process.argv.includes('--review-only'))return;
    await page.locator('#comparisonLocate').click();await page.locator('#comparisonDialog').waitFor({state:'hidden'});
    await page.getByRole('textbox',{name:'标签',exact:true}).waitFor();
    assert.equal(await page.getByRole('textbox',{name:'标签',exact:true}).inputValue(),'ID.PC');
    assert.equal((await scene()).components.find(c=>c.factory==='Register'&&c.label==='ID.PC').location.x,640);
    await page.locator('#agentTab').click();
    await page.locator('#questionInput').fill('我在检查 ID.PC 的布线，稍后继续讨论。');
    await page.locator('#proposalTab').click();
    await page.locator('.candidate-card').getByRole('button',{name:'查看改动'}).click();await reviewReady('连接关系未变');
    await page.locator('#comparisonEvidence').click();
    await waitUntil(()=>page.locator('#evidenceResults').textContent().then(t=>t.includes('尚未运行输入输出检查')));
    await page.locator('#evidenceTrace').click();
    assert.match(await page.locator('#evidenceResults').textContent(),/尚未观察时钟执行/);
    await page.locator('#evidenceBack').click();await reviewReady('连接关系未变');
    await reviewRow(/^ID.PC$/).click();
    const initial=await session();
    await page.locator('#comparisonPrimary').click();await page.locator('#comparisonDialog').waitFor({state:'hidden',timeout:60000});
    const applied=await changed(initial.revision.id);
    await page.getByRole('textbox',{name:'标签',exact:true}).waitFor();
    assert.equal(await page.getByRole('textbox',{name:'标签',exact:true}).inputValue(),'ID.PC','applied candidate remains selected for human editing');
    assert.equal((await scene()).components.find(c=>c.factory==='Register'&&c.label==='ID.PC').location.x,740);
    const label=page.getByRole('textbox',{name:'标签',exact:true});await label.fill('ID.PC.REG');await label.press('Enter');
    const renamed=await changed(applied.revision.id);
    await history(0);await reviewReady('连接关系未变');
    assert.equal(await page.locator('.comparison-row').count(),1,'latest human change compares against its own before version');
    await reviewRow('ID.PC.REG').click();
    assert.match(await page.locator('#comparisonDetails').textContent(),/名称ID.PCID.PC.REG/);
    await page.screenshot({path:output+'/04-human-edit.png'});
    await page.locator('#comparisonLocate').click();await page.locator('#comparisonDialog').waitFor({state:'hidden'});
    await page.getByRole('textbox',{name:'标签',exact:true}).waitFor();
    assert.equal(await page.getByRole('textbox',{name:'标签',exact:true}).inputValue(),'ID.PC.REG');
    await page.locator('#fitButton').click();
    const p=await world({x:940,y:100});await page.mouse.click(p.x,p.y);
    assert.equal(await page.locator('.wire-group.is-selected-wire').count(),1);
    await page.locator('#deleteSelectionButton').click();const disconnected=await changed(renamed.revision.id);
    const broken=connection(await scene());assert.notDeepEqual(broken.Register,broken.Pin);
    await history(0);await reviewReady('信号连接发生变化');
    await page.locator('[data-category="connections"]').click();
    assert.equal(await page.locator('.comparison-row').count(),1);
    await page.locator('.comparison-row').click();
    assert.match(await page.locator('#comparisonDetails').textContent(),/32 位连接改变/);
    assert.match(await page.locator('#comparisonDetails').textContent(),/输出 Q \[31:0\]/);
    assert.match(await page.locator('#comparisonDetails').textContent(),/电路输出 \[31:0\]/);
    await waitUntil(()=>page.locator('#comparisonDetailImage').getAttribute('href'));
    await page.screenshot({path:output+'/05-disconnected.png'});
    await page.locator('#comparisonClose').click();
    await history(1);await reviewReady('连接关系未变');
    await page.locator('#comparisonMode').selectOption('current');await reviewReady('信号连接发生变化');
    await page.locator('[data-category="connections"]').click();await page.locator('.comparison-row').click();
    await page.locator('#comparisonPrimary').click();await page.locator('#comparisonDialog').waitFor({state:'hidden',timeout:60000});
    const restored=await changed(disconnected.revision.id);
    assert.equal(restored.revision.id,renamed.revision.id);
    const reconnected=connection(await scene());assert.deepEqual(reconnected.Register,reconnected.Pin);
    assert.deepEqual(fs.readFileSync(source),original,'review/apply/manual edits/restore never autosave');
    await page.locator('#agentTab').click();
    assert.equal(await page.locator('#questionInput').inputValue(),'我在检查 ID.PC 的布线，稍后继续讨论。');
    await page.locator('#fitButton').click();await page.screenshot({path:output+'/06-continue-editing.png'});
    await page.locator('#circuitCanvas').press('ControlOrMeta+s');await waitUntil(()=>session().then(s=>!s.workspace.dirty));
    const saved=await session();
    await app.close();app=await launch();page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
    await page.setViewportSize({width:1500,height:960});
    await page.locator('#circuitList .circuit-item').filter({has:page.locator('strong',{hasText:/^IF_ID$/})}).click({timeout:90000});await idle();
    assert.equal((await session()).workspace.id,initial.workspace.id);
    assert.equal((await session()).revision.id,saved.revision.id);
    const reopened=connection(await scene());assert.deepEqual(reopened.Register,reopened.Pin);
    fs.writeFileSync(output+'/result.json',JSON.stringify({root,modelTurns:0,source,projectId:initial.workspace.id,
      revisions:{initial:initial.revision.id,applied:applied.revision.id,renamed:renamed.revision.id,disconnected:disconnected.revision.id,restored:restored.revision.id},
      layoutOnly:true,bitCount:32,broken,reconnected,draftPreserved:true,explicitSave:true,reopen:true,errors},null,2));
    assert.deepEqual(errors,[]);
    console.log(root);
  }catch(error){if(page)await page.screenshot({path:output+'/failure.png'}).catch(()=>{});console.error(errors);throw error;}
  finally{await app.close();}
}
main().catch(e=>{console.error(e.stack||e);process.exitCode=1;});
